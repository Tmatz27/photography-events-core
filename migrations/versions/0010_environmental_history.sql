-- Quantities, forecasts and publications are not biological observations.
ALTER TABLE source_runs ADD COLUMN native_evidence_asof TIMESTAMPTZ;
CREATE OR REPLACE VIEW source_health_current AS
 SELECT s.key,s.enabled,last_run.started_at AS last_attempt_at,last_run.status,
 last_run.error_code,last_success.completed_at AS last_success_at,last_success.provider_updated_at,
 last_success.native_evidence_asof
 FROM sources s
 LEFT JOIN LATERAL(SELECT * FROM source_runs r WHERE r.source_id=s.id ORDER BY completed_at DESC,id DESC LIMIT 1) last_run ON TRUE
 LEFT JOIN LATERAL(SELECT * FROM source_runs r WHERE r.source_id=s.id AND status='success' ORDER BY completed_at DESC,id DESC LIMIT 1) last_success ON TRUE;
CREATE TABLE environmental_assertions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 raw_observation_id BIGINT NOT NULL REFERENCES raw_observations(id) ON DELETE CASCADE,
 source_run_id BIGINT NOT NULL REFERENCES source_runs(id),
 dataset_key TEXT NOT NULL,
 station_id TEXT NOT NULL,
 quantity TEXT NOT NULL,
 evidence_kind TEXT NOT NULL CHECK(evidence_kind IN ('measurement','forecast','reference','publication')),
 observed_at TIMESTAMPTZ,
 valid_at TIMESTAMPTZ,
 issued_at TIMESTAMPTZ,
 provider_updated_at TIMESTAMPTZ,
 native_value TEXT,
 numeric_value NUMERIC,
 unit TEXT,
 quality JSONB NOT NULL CHECK(jsonb_typeof(quality)='object'),
 provider_geometry geometry(Point,4326),
 metadata JSONB NOT NULL CHECK(jsonb_typeof(metadata)='object'),
 raw_payload JSONB,
 content_sha256 TEXT NOT NULL,
 recorded_at TIMESTAMPTZ NOT NULL,
 last_received_at TIMESTAMPTZ NOT NULL,
 superseded_at TIMESTAMPTZ,
 withdrawn BOOLEAN NOT NULL DEFAULT FALSE,
 CHECK(evidence_kind NOT IN ('measurement','forecast') OR (valid_at IS NOT NULL AND unit IS NOT NULL)),
 CHECK(evidence_kind!='forecast' OR issued_at IS NOT NULL),
 CHECK(numeric_value IS NULL OR numeric_value NOT IN ('NaN'::numeric,'Infinity'::numeric,'-Infinity'::numeric))
);
CREATE UNIQUE INDEX environmental_one_current ON environmental_assertions(raw_observation_id) WHERE superseded_at IS NULL;
CREATE INDEX environmental_dataset_time ON environmental_assertions(dataset_key,station_id,valid_at);
CREATE INDEX environmental_source_run ON environmental_assertions(source_run_id);
CREATE INDEX environmental_geometry ON environmental_assertions USING gist(provider_geometry);
